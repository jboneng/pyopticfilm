@dataclass(frozen=True)
class Model8200i:
    name: str = "plustek-opticfilm-8200i"
    vendor: str = "PLUSTEK"
    model: str = "OpticFilm 8200i"
    asic: str = "GL845"
    usb_vendor_id: int = 0x07B3
    usb_product_id: int = 0x130D

    #: Locked out until live-validated in a future release (SANE tables only).
    scan_ready: bool = False

    resolutions_dpi: tuple[int, ...] = (7200, 3600, 1800, 900)
    bpp_gray: tuple[int, ...] = (16,)
    bpp_color: tuple[int, ...] = (16,)
    supports_infrared: bool = True

    x_size_mm: float = 36.0
    y_size_mm: float = 44.0
    x_offset_ta_mm: float = 0.5
    y_offset_ta_mm: float = 28.5
    x_size_ta_mm: float = 36.33
    y_size_ta_mm: float = 25.0

    # Shading calib strip (tables_model.cpp)
    x_size_calib_mm: float = 36.83
    y_size_calib_ta_mm: float = 2.0
    y_offset_calib_white_ta_mm: float = 0.0
    y_offset_sensor_to_ta_mm: float = 0.0

    ld_shift_r: int = 0
    ld_shift_g: int = 12
    ld_shift_b: int = 24

    # Per-DPI Y stagger (tables_sensor.cpp); only 7200 uses StaggerConfig{4,0}
    stagger_y_by_dpi: Mapping[int, tuple[int, ...]] = field(
        default_factory=lambda: {900: (), 1800: (), 3600: (), 7200: (4, 0)}
    )
    register_dpiset_by_dpi: Mapping[int, int] = field(
        default_factory=lambda: dict(_REGISTER_DPISET_8200I)
    )
    output_pixel_offset_by_dpi: Mapping[int, int] = field(
        default_factory=lambda: dict(_OUTPUT_PIXEL_OFFSET_8200I)
    )

    register_dpihw: int = 1200
    exposure_lperiod: int = 14000
    #: SANE tables_sensor: constant 14000 for colour and IR.
    lperiod_by_dpi: Mapping[tuple[str, int] | int, int] = field(
        default_factory=lambda: {
            ("transparency", 900): 14000,
            ("transparency", 1800): 14000,
            ("transparency", 3600): 14000,
            ("transparency", 7200): 14000,
            ("infrared", 900): 14000,
            ("infrared", 1800): 14000,
            ("infrared", 3600): 14000,
            ("infrared", 7200): 14000,
        }
    )
    #: LED settle after the lamp turns on before an image capture (s).
    lamp_settle_s: float = 0.5

    dummy_pixel: int = 20
    motor_base_ydpi: int = 3600
    optical_resolution: int = 7200
    motor_profile: MotorProfile = DEFAULT_GL845_MOTOR

    init_regs: Mapping[int, int] = field(default_factory=lambda: dict(_INIT_REGS_8200I))
    sensor_custom_regs: Mapping[int, int] = field(
        default_factory=lambda: dict(_SENSOR_CUSTOM_8200I)
    )
    frontend_regs: Mapping[int, int] = field(default_factory=lambda: dict(_FRONTEND_8200I))
    gpo_regs: Mapping[int, int] = field(default_factory=lambda: dict(_GPO_8200I))
    memory_layout_regs: Mapping[int, int] = field(
        default_factory=lambda: dict(_MEMORY_LAYOUT_8200I)
    )

    @property
    def max_area_mm(self) -> tuple[float, float]:
        return (self.x_size_ta_mm, self.y_size_ta_mm)

    def boot_register_map(self) -> dict[int, int]:
        """Init regs with sensor custom overlay and dpihw applied."""
        regs = dict(self.init_regs)
        regs.update(self.sensor_custom_regs)
        regs[0x05] = (regs.get(0x05, 0) & ~0xC0) | 0x40  # dpihw=1200
        return regs


MODEL_8200I = Model8200i()
